def build_symbol_names() -> dict[str, str]:
    """构建代码→名称映射（静态+持仓表补充）。"""
    names = dict(STOCK_NAMES)
    for t in repo.get_traders(active_only=False):
        for p in repo.get_positions(t.id):
            if p.symbol not in names and p.name:
                names[p.symbol] = p.name
    return names
